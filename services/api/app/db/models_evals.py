"""SQLAlchemy models for Phase 2 eval gates.

Tables:
- counterfactual_perturbations: one row per perturbation generated against a brief.
- counterfactual_gate_runs: one row per (run, brief_kind, brief_id) gate aggregate.
- leakage_holdout_cases: each holdout case computes full vs restricted decisions.
- leakage_runs: each aggregate over a set of cases (with run_id when generated by
  a research run, null when generated by the standalone harness).
- human_reviews: weekly two-axis human reviews.
"""

import uuid
from datetime import UTC, date, datetime
from enum import StrEnum

from sqlalchemy import (
    JSON,
    Boolean,
    CheckConstraint,
    Date,
    DateTime,
    Float,
    ForeignKey,
    Index,
    Integer,
    SmallInteger,
    String,
    Text,
    UniqueConstraint,
    Uuid,
    func,
)
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base


class BriefKind(StrEnum):
    macro = "macro"
    sector = "sector"
    company = "company"
    portfolio = "portfolio"


class PerturbationKind(StrEnum):
    drop_top_evidence = "drop_top_evidence"
    flip_top_call_direction = "flip_top_call_direction"
    redact_top_quote = "redact_top_quote"
    lower_top_call_conviction = "lower_top_call_conviction"
    swap_call_ordering = "swap_call_ordering"


def _utcnow() -> datetime:
    return datetime.now(UTC)


class CounterfactualPerturbation(Base):
    __tablename__ = "counterfactual_perturbations"
    __table_args__ = (
        CheckConstraint(
            "brief_kind IN ('macro', 'sector', 'company', 'portfolio')",
            name="ck_counterfactual_perturbations_brief_kind",
        ),
        Index(
            "ix_counterfactual_perturbations_run_id_brief_kind",
            "run_id",
            "brief_kind",
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)
    run_id: Mapped[uuid.UUID] = mapped_column(
        Uuid,
        ForeignKey("research_runs.id", ondelete="CASCADE"),
        nullable=False,
    )
    brief_kind: Mapped[str] = mapped_column(String(16), nullable=False)
    brief_id: Mapped[uuid.UUID | None] = mapped_column(Uuid, nullable=True)
    perturbation_kind: Mapped[str] = mapped_column(String(64), nullable=False)
    perturbation_input: Mapped[dict[str, object]] = mapped_column(
        JSON, nullable=False
    )
    baseline_output: Mapped[dict[str, object]] = mapped_column(JSON, nullable=False)
    perturbed_output: Mapped[dict[str, object]] = mapped_column(JSON, nullable=False)
    decision_delta: Mapped[dict[str, object]] = mapped_column(JSON, nullable=False)
    is_meaningful: Mapped[bool] = mapped_column(Boolean, nullable=False)
    decision_changed: Mapped[bool] = mapped_column(Boolean, nullable=False)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        default=_utcnow,
    )


class CounterfactualGateRun(Base):
    __tablename__ = "counterfactual_gate_runs"
    __table_args__ = (
        CheckConstraint(
            "brief_kind IN ('macro', 'sector', 'company', 'portfolio')",
            name="ck_counterfactual_gate_runs_brief_kind",
        ),
        UniqueConstraint(
            "run_id",
            "brief_kind",
            "brief_id",
            name="uq_counterfactual_gate_runs_run_kind_brief",
        ),
        Index("ix_counterfactual_gate_runs_run_id", "run_id"),
    )

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)
    run_id: Mapped[uuid.UUID] = mapped_column(
        Uuid,
        ForeignKey("research_runs.id", ondelete="CASCADE"),
        nullable=False,
    )
    brief_kind: Mapped[str] = mapped_column(String(16), nullable=False)
    brief_id: Mapped[uuid.UUID | None] = mapped_column(Uuid, nullable=True)
    perturbation_count: Mapped[int] = mapped_column(Integer, nullable=False)
    meaningful_count: Mapped[int] = mapped_column(Integer, nullable=False)
    meaningful_changed_count: Mapped[int] = mapped_column(Integer, nullable=False)
    change_rate: Mapped[float] = mapped_column(Float, nullable=False)
    threshold: Mapped[float] = mapped_column(Float, nullable=False)
    passed: Mapped[bool] = mapped_column(Boolean, nullable=False)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        default=_utcnow,
    )


class LeakageHoldoutCase(Base):
    __tablename__ = "leakage_holdout_cases"
    __table_args__ = (
        UniqueConstraint(
            "case_name", "cutoff_at", name="uq_leakage_holdout_cases_name_cutoff"
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)
    case_name: Mapped[str] = mapped_column(String(128), nullable=False)
    cutoff_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    full_decision: Mapped[dict[str, object]] = mapped_column(JSON, nullable=False)
    restricted_decision: Mapped[dict[str, object]] = mapped_column(JSON, nullable=False)
    agreement: Mapped[float] = mapped_column(Float, nullable=False)
    decay: Mapped[float] = mapped_column(Float, nullable=False)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        default=_utcnow,
    )


class LeakageRun(Base):
    __tablename__ = "leakage_runs"
    __table_args__ = (Index("ix_leakage_runs_run_id", "run_id"),)

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)
    run_id: Mapped[uuid.UUID | None] = mapped_column(
        Uuid,
        ForeignKey("research_runs.id", ondelete="SET NULL"),
        nullable=True,
    )
    case_count: Mapped[int] = mapped_column(Integer, nullable=False)
    mean_decay: Mapped[float] = mapped_column(Float, nullable=False)
    max_decay: Mapped[float] = mapped_column(Float, nullable=False)
    threshold: Mapped[float] = mapped_column(Float, nullable=False)
    flagged: Mapped[bool] = mapped_column(Boolean, nullable=False)
    case_ids: Mapped[list[str]] = mapped_column(JSON, nullable=False, default=list)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        default=_utcnow,
    )


class HumanReview(Base):
    __tablename__ = "human_reviews"
    __table_args__ = (
        CheckConstraint(
            "brief_kind IS NULL OR "
            "brief_kind IN ('macro', 'sector', 'company', 'portfolio')",
            name="ck_human_reviews_brief_kind",
        ),
        CheckConstraint(
            "surfaced_missed BETWEEN -2 AND 2",
            name="ck_human_reviews_surfaced_missed_range",
        ),
        CheckConstraint(
            "missed_noticed BETWEEN -2 AND 2",
            name="ck_human_reviews_missed_noticed_range",
        ),
        Index("ix_human_reviews_week_start", "week_start"),
        Index("ix_human_reviews_run_id", "run_id"),
    )

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)
    run_id: Mapped[uuid.UUID | None] = mapped_column(
        Uuid,
        ForeignKey("research_runs.id", ondelete="SET NULL"),
        nullable=True,
    )
    brief_kind: Mapped[str | None] = mapped_column(String(16), nullable=True)
    week_start: Mapped[date] = mapped_column(Date, nullable=False)
    reviewer: Mapped[str] = mapped_column(String(128), nullable=False)
    surfaced_missed: Mapped[int] = mapped_column(SmallInteger, nullable=False)
    missed_noticed: Mapped[int] = mapped_column(SmallInteger, nullable=False)
    notes: Mapped[str | None] = mapped_column(Text, nullable=True)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        default=_utcnow,
    )


__all__ = [
    "BriefKind",
    "CounterfactualGateRun",
    "CounterfactualPerturbation",
    "HumanReview",
    "LeakageHoldoutCase",
    "LeakageRun",
    "PerturbationKind",
]
